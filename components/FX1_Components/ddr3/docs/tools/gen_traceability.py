def subtask(req_id: str, test_ids: str) -> str:
    if req_id.startswith(("CSR-", "LC-")):
        return "2"
    if req_id.startswith(("FE-", "BE-")):
        return "3"
    if re.search(r"VP-(CFG|PROFILE)", test_ids):
        return "1-2"
    return "2-3"


def rows():
    for name in AUDITS:
        for line in (DOCS / name).read_text(encoding="utf-8").splitlines():
            if not re.match(r"^\|\s*(FE|BE|IF|LC|CSR)-[0-9]", line):
                continue
            cells = [c.strip() for c in line.strip().strip("|").split("|")]
            if len(cells) < 5:
                continue
            req_id, source, text, vp_class, tests = cells[0], cells[1], cells[2], cells[3], cells[4]
            yield name, req_id, source, text, vp_class, tests


def main():
    out = ["# DDR3 Controller VP — Requirement Traceability", "",
           "Generated by `docs/tools/gen_traceability.py` from the P0 audits. Do not edit by hand;",
           "change the audits or the STATUS table in the script and regenerate.", "",
           "Columns: requirement (audit ID, linked to its audit), VP class, proposed tests, owning",
           "subtask, status, spec dependency (DEC-13 provisional encodings / [spec_owner_questions.md](spec_owner_questions.md)).", "",
           "Status values: `Planned`, `Partial S<n>`, `Done S<n>`, `Limitation` (agreed VP limit, see",
           "[limitations.md](limitations.md)), `OUT` (excluded by the spec), `n/a` (ABSTRACTED below the",
           "VP level, documented in architecture.md).", ""]
    summary = {}
    body = ["| Req | Class | Tests | Subtask | Status | Spec dep | Evidence |", "|---|---|---|---|---|---|---|"]
    for name, req_id, source, text, vp_class, tests in rows():
        dep = sorted({soq for pat, soq in BLOCKED if re.search(pat, text)})
        cls = vp_class.split()[0].strip("*").upper() if vp_class else "?"
        if req_id in STATUS:
            status, evidence = STATUS[req_id]
        elif cls == "OUT":
            status, evidence = "OUT", ""
        elif cls == "ABSTRACTED":
            status, evidence = "n/a", ""
        else:
            status, evidence = "Planned", ""
        dep = [d + " (provisional)" for d in dep]
        summary[status] = summary.get(status, 0) + 1
        anchor = f"[{req_id}]({name})"
        body.append(f"| {anchor} | {cls} | {tests} | {subtask(req_id, tests)} | {status} | "
                    f"{', '.join(dep)} | {evidence} |")
    out.append("## Summary")
    out.append("")
    out.append("| Status | Requirements |")
    out.append("|---|---|")
    for k in sorted(summary):
        out.append(f"| {k} | {summary[k]} |")
    out.append(f"| **Total** | **{sum(summary.values())}** |")
    out.append("")
    out.append("## Matrix")
    out.append("")
    out.extend(body)
    OUT.write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"wrote {OUT} ({sum(summary.values())} requirements)")


if __name__ == "__main__":
    main()
