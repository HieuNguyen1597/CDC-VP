def small_k(kh, kw, cin, cout, tile, h=None, w=None, extra=None):
    """One layer without padding for the short-context set; the image defaults to one tile."""
    th, tw = tile[1], tile[2]
    h, w = h or th + kh - 1, w or tw + kw - 1
    name = "K %d (%dx%d cin %d) no padding, image %dx%d, tile %d %d %d %s" % (
        cin * kh * kw, kh, kw, cin, h, w, tile[0], th, tw, " ".join("%s=%d" % kv for kv in sorted((extra or {}).items())))
    return (name, cin, h, w, cout, kh, kw, 1, 0, None, tile, extra or {})


