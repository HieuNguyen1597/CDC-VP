#!/usr/bin/env python3
"""Check program for convolution padding: padding per side and padding value.

Writes a program directory (mmio.txt, dram_init.bin, dram_golden.bin) with small GEMM_FUSED instructions on random
data. The network programs of this package only use one symmetric PAD and the padding value 0; this program covers
the other forms of the extension registers PAD_VALUE, PAD_T, PAD_L, PAD_B, PAD_R.

--set fixed (default), 13 instructions:
  symmetric PAD with value 0 (the old form) and the same layer through the four registers with a non-zero value;
  padding only below / right (stride 2, the TensorFlow "SAME" rule) and only above / left;
  kernels 5 x 5, 5 x 3 and 7 x 7 with two and three rows / columns of padding, equal and unequal sides;
  a layer of several tiles in both directions, a tile width rounded up (FLAGS bit 0), an input-channel split;
  a 1 x 1 layer with padding.
--set random --count N: N layers with random image size, kernel (1 to 7, also rectangular), stride 1 or 2, padding
  0 .. kernel - 1 on each side, padding value, tile size, optional FLAGS bit 0, Y_USED and TILE_CIN, plus three fixed
  layers: a tile that nearly fills one input buffer of the hardware, stride 2 with 32 positions per context, and
  several output-channel tiles over several spatial tiles.
--set probe: four layers. Two 3 x 1 layers with padding above / below only: in the first the row width is 32, so the real part of
  the window and the padded window start every row and channel on a word boundary; in the second (width 30) they do
  not. Used to see whether the timing of the feeder flags depends on that alignment.
--set smallk: layers without padding whose core contexts are very short (K = kernel positions x input channels of the
  core pass from 1 to 10), mostly with 32 output channels per tile; see the comment at SMALLK.
--set dilation: 13 layers with the DILATION register (2, 3, 4, 9): with and without padding, the old PAD form,
  stride 2, kernels 3x3, 5x5, 1x3, 3x1, a 1x1 layer, and 8 taps 9 apart (effective kernel 64, the width of the
  dilation pattern of the IFMAP feeder), several tiles, a tile width rounded up, an input-channel split, two contexts
  per output row.
--set dilrandom --count N: N random layers with DILATION 2 to 9 (kernel 1 to 5, (kw - 1) x DILATION <= 63), random
  padding per side up to the effective kernel, padding value, stride, tile, optional FLAGS bit 0, Y_USED, TILE_CIN.
  A separate random stream from --set random, so that set does not change.

dram_golden.bin is computed here in coordinates of the unpadded image (explicit loops for the fixed set, index arrays
with a validity mask for the others; no shared code with the model or with tools/has/ref_program.py), so three results
can be compared: this file, ref_program.py and the model, with the padding staged by the data flow controller or
generated by the IFMAP feeder (HAS_FEEDER_PAD=1).

Usage: python3 tools/has/make_pad_gate.py <out dir> [--seed N] [--set fixed|random|probe|smallk|dilation|dilrandom]
                                          [--count N]
"""
