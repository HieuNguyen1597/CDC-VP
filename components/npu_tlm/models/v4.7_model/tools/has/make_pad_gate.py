def out_size(n, k, s, before, after, d=1):
    return (n + before + after - ((k - 1) * d + 1)) // s + 1


def random_cases(rng, count):
    """Random layers inside the limits of one tile; the label carries the whole geometry."""
    cases = []
    while len(cases) < count:
        kh, kw = int(rng.choice([1, 2, 3, 3, 3, 5, 7])), int(rng.choice([1, 2, 3, 3, 3, 5, 7]))
        s = int(rng.choice([1, 1, 2]))
        cin = int(rng.choice([1, 3, 8, 16, 32]))
        cout = int(rng.choice([4, 8, 16, 32]))
        h, w = int(rng.integers(max(kh, 2), 41)), int(rng.integers(max(kw, 2), 41))
        if rng.random() < 0.2:
            p = int(rng.integers(0, min(kh, kw)))
            pads, val = p, None                                    # old form: one PAD, value 0
            pt = pl = pb = pr = p
        else:
            pt, pb = int(rng.integers(0, kh)), int(rng.integers(0, kh))
            pl, pr = int(rng.integers(0, kw)), int(rng.integers(0, kw))
            pads, val = (pt, pl, pb, pr), int(rng.integers(-128, 128))
        if h + pt + pb < kh or w + pl + pr < kw:
            continue
        oh, ow = out_size(h, kh, s, pt, pb), out_size(w, kw, s, pl, pr)
        cout_t = cout if rng.random() < 0.7 else cout // 2
        h_t, w_t = int(rng.integers(1, oh + 1)), int(rng.integers(1, ow + 1))
        extra = {}
        if rng.random() < 0.25:
            extra["FLAGS"] = 1
        if rng.random() < 0.25:
            div = [d for d in range(1, 33) if w_t % d == 0]
            extra["Y_USED"] = int(rng.choice(div))
        cin_t = cin
        if cin >= 16 and rng.random() < 0.3:
            cin_t = cin // 2
            extra["TILE_CIN"] = cin_t
        # one tile must fit the buffers (width after rounding up to 32 when FLAGS bit 0 is set)
        wt_max = (w_t + 31) // 32 * 32 if extra.get("FLAGS") else w_t
        if (cin_t * ((h_t - 1) * s + kh) * ((wt_max - 1) * s + kw) > CAP_A or cout_t * cin_t * kh * kw > CAP_B
                or cout_t * h_t * wt_max > CAP_C):
            continue
        name = "random %dx%d s%d cin %d %dx%d cout %d pads %s value %s tile %d %d %d %s" % (
            kh, kw, s, cin, h, w, cout, pads, val, cout_t, h_t, w_t, " ".join("%s=%d" % kv for kv in sorted(extra.items())))
        cases.append((name, cin, h, w, cout, kh, kw, s, pads, val, (cout_t, h_t, w_t), extra))
    # a tile that nearly fills one input buffer: 64 x 35 x 35 = 78400 bytes with the padding, 73984 without
    cases.append(("3x3 s1 pads 1 1 1 1, value -128, input window 78400 bytes", 64, 34, 34, 8, 3, 3, 1, (1, 1, 1, 1), -128,
                  (8, 33, 33), {}))
    # stride 2 with 32 positions per context (the widest row sweep of the feeder, the shape of the YOLOv8m stem)
    cases.append(("3x3 s2 pads 1 1 1 1, value -128, 32 positions per context", 8, 64, 64, 8, 3, 3, 2, (1, 1, 1, 1), -128,
                  (8, 4, 32), {}))
    # four output-channel tiles over four spatial tiles: the input window is kept in SRAM-A while the channel tiles cycle
    cases.append(("3x3 s1 pads 1 1 1 1, value 9, 4 channel tiles x 4 spatial tiles", 8, 16, 16, 16, 3, 3, 1, (1, 1, 1, 1), 9,
                  (4, 8, 8), {}))
    return cases


def random_dil_cases(rng, count):
    """Random layers with dilation 2 to 9 inside the limits of one tile; the label carries the whole geometry."""
    cases = []
    while len(cases) < count:
        kh, kw = int(rng.choice([1, 2, 3, 3, 5])), int(rng.choice([1, 2, 3, 3, 5]))
        d = int(rng.integers(2, 10))
        if kh == 1 and kw == 1 or (kw - 1) * d > 63:
            continue
        ekh, ekw = (kh - 1) * d + 1, (kw - 1) * d + 1
        s = int(rng.choice([1, 1, 2]))
        cin = int(rng.choice([1, 3, 8, 16]))
        cout = int(rng.choice([4, 8, 16, 32]))
        h, w = int(rng.integers(2, 49)), int(rng.integers(2, 49))
        pt, pb = int(rng.integers(0, min(ekh, 13))), int(rng.integers(0, min(ekh, 13)))
        pl, pr = int(rng.integers(0, min(ekw, 13))), int(rng.integers(0, min(ekw, 13)))
        if h + pt + pb < ekh or w + pl + pr < ekw:
            continue
        pads, val = (pt, pl, pb, pr), int(rng.integers(-128, 128))
        oh, ow = out_size(h, kh, s, pt, pb, d), out_size(w, kw, s, pl, pr, d)
        cout_t = cout if rng.random() < 0.7 else cout // 2
        h_t, w_t = int(rng.integers(1, oh + 1)), int(rng.integers(1, ow + 1))
        extra = {"DILATION": d}
        if rng.random() < 0.25:
            extra["FLAGS"] = 1
        if rng.random() < 0.25:
            extra["Y_USED"] = int(rng.choice([v for v in range(1, 33) if w_t % v == 0]))
        cin_t = cin
        if cin >= 16 and rng.random() < 0.3:
            cin_t = cin // 2
            extra["TILE_CIN"] = cin_t
        wt_max = (w_t + 31) // 32 * 32 if extra.get("FLAGS") else w_t
        if (cin_t * ((h_t - 1) * s + ekh) * ((wt_max - 1) * s + ekw) > CAP_A or cout_t * cin_t * kh * kw > CAP_B
                or cout_t * h_t * wt_max > CAP_C):
            continue
        name = "random dilation %d %dx%d s%d cin %d %dx%d cout %d pads %s value %d tile %d %d %d %s" % (
            d, kh, kw, s, cin, h, w, cout, pads, val, cout_t, h_t, w_t,
            " ".join("%s=%d" % kv for kv in sorted(extra.items()) if kv[0] != "DILATION"))
        cases.append((name, cin, h, w, cout, kh, kw, s, pads, val, (cout_t, h_t, w_t), extra))
    return cases


def reference_loops(x, wt, bias, S, sh, zp, s, pt, pl, pv, oh, ow, d=1):
    """Explicit loops over output positions and kernel taps, in coordinates of the unpadded image (taps d apart)."""
    cout, cin, kh, kw = wt.shape
    h, w = x.shape[1:]
    q = np.zeros((cout, oh, ow), dtype=np.int64)
    for oy in range(oh):
        for ox in range(ow):
            acc = bias.copy()
            for ky in range(kh):
                for kx in range(kw):
                    iy, ix = oy * s + ky * d - pt, ox * s + kx * d - pl
                    col = x[:, iy, ix] if (0 <= iy < h and 0 <= ix < w) else np.full(cin, pv, dtype=np.int64)
                    acc += wt[:, :, ky, kx] @ col
            for c in range(cout):
                v = (int(acc[c]) * int(S[c]) + (1 << (int(sh[c]) - 1))) >> int(sh[c])   # round half up
                v = max(-32768, min(32767, v)) + zp
                q[c, oy, ox] = max(-128, min(127, v))
    return q


def reference_indexed(x, wt, bias, S, sh, zp, s, pt, pl, pv, oh, ow, d=1):
    """Same arithmetic with index arrays: every tap reads x[iy, ix] where the position is inside the image, else pv."""
    cout, cin, kh, kw = wt.shape
    h, w = x.shape[1:]
    acc = np.zeros((cout, oh, ow), dtype=np.int64) + bias[:, None, None]
    oy, ox = np.arange(oh)[:, None], np.arange(ow)[None, :]
    for ky in range(kh):
        for kx in range(kw):
            iy, ix = oy * s + ky * d - pt, ox * s + kx * d - pl
            inside = (iy >= 0) & (iy < h) & (ix >= 0) & (ix < w)
            tap = x[:, np.clip(iy, 0, h - 1), np.clip(ix, 0, w - 1)]                 # [cin, oh, ow]
            tap = np.where(inside[None, :, :], tap, pv)
            acc += np.einsum("oc,cyx->oyx", wt[:, :, ky, kx], tap)
    v = (acc * S[:, None, None] + (np.int64(1) << (sh[:, None, None] - 1))) >> sh[:, None, None]
    v = np.clip(v, -32768, 32767) + zp
    return np.clip(v, -128, 127)


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("out")
    ap.add_argument("--seed", type=int, default=1)
    ap.add_argument("--set", choices=("fixed", "random", "probe", "smallk", "dilation", "dilrandom"), default="fixed")
    ap.add_argument("--count", type=int, default=40)
    a = ap.parse_args()
    rng = np.random.default_rng(a.seed)
    if a.set == "dilrandom":
        cases = random_dil_cases(np.random.default_rng(1000 + a.seed), a.count)
    else:
        cases = {"fixed": CASES, "probe": PROBE, "smallk": SMALLK, "dilation": DILATION}.get(a.set) or random_cases(rng, a.count)
    img = bytearray(512 * 1024)
    top = [0x1000]

    def alloc(n):
        p = top[0]
        top[0] = (p + n + 63) & ~63
        if top[0] > len(img):
            img.extend(bytes(max(top[0] - len(img), 1 << 20)))
        return p

    def put(arr, dtype):
        arr = np.asarray(arr, dtype=dtype).ravel()
        p = alloc(arr.nbytes)
        img[p:p + arr.nbytes] = arr.tobytes()
        return p

    prog, golden = [], []
    for name, cin, h, w, cout, kh, kw, s, pads, val, tile, extra in cases:
        pt, pl, pb, pr = (pads,) * 4 if isinstance(pads, int) else pads
        pv = 0 if val is None else val
        d = extra.get("DILATION", 1)
        oh, ow = out_size(h, kh, s, pt, pb, d), out_size(w, kw, s, pl, pr, d)
        x = rng.integers(-100, 101, size=(cin, h, w), dtype=np.int64)
        wt = rng.integers(-20, 21, size=(cout, cin, kh, kw), dtype=np.int64)
        bias = rng.integers(-2000, 2001, size=cout, dtype=np.int64)
        S = rng.integers(1 << 29, 1 << 30, size=cout, dtype=np.int64)
        sh = rng.integers(38, 41, size=cout, dtype=np.int64)
        zp = int(rng.integers(-5, 6))
        # weights: one block per output-channel range of TILE_COUT channels, laid out [c][kh][kw][k of the range]
        cout_t = tile[0]
        assert cout % cout_t == 0
        K = cin * kh * kw
        w_addr = alloc(cout * K)
        for c0 in range(0, cout, cout_t):
            blk = np.transpose(wt[c0:c0 + cout_t], (1, 2, 3, 0)).astype(np.int8)
            img[w_addr + c0 * K:w_addr + c0 * K + blk.size] = blk.tobytes()
        regs = {"in": put(x, np.int8), "w": w_addr, "out": alloc(cout * oh * ow), "bias": put(bias, "<i4"), "kh": kh, "kw": kw,
                "stride": s, "pad": pads if isinstance(pads, int) else 0, "act": 0, "has_skip": 0,
                "IN_C": cin, "IN_H": h, "IN_W": w, "OUT_C": cout, "OUT_H": oh, "OUT_W": ow,
                "TILE_COUT": tile[0], "TILE_H": tile[1], "TILE_W": tile[2],
                "SCALE_ADDR": put(S, "<i4"), "SHIFT_ADDR": put(sh, "<i4"), "ZP_OUT": zp, "FLAGS": 0}
        if not isinstance(pads, int):
            regs.update({"PAD_T": pt, "PAD_L": pl, "PAD_B": pb, "PAD_R": pr})
        if val is not None:
            regs["PAD_VALUE"] = val
        regs.update(extra)
        prog.append((name, regs))
        ref = reference_loops if a.set in ("fixed", "smallk", "dilation") else reference_indexed
        golden.append((regs["out"], ref(x, wt, bias, S, sh, zp, s, pt, pl, pv, oh, ow, d).astype(np.int8)))

    size = max(512 * 1024, math.ceil(top[0] / 4096) * 4096)
    del img[size:]
    os.makedirs(a.out, exist_ok=True)
    with open(os.path.join(a.out, "dram_init.bin"), "wb") as f:
        f.write(img)
    gold = bytearray(img)
    for addr, q in golden:
        gold[addr:addr + q.size] = q.tobytes()
    with open(os.path.join(a.out, "dram_golden.bin"), "wb") as f:
        f.write(gold)
    with open(os.path.join(a.out, "mmio.txt"), "w", newline="\n") as f:
        f.write("# make_pad_gate.py --set %s --seed %d: %d instructions, image %d B\n" % (a.set, a.seed, len(prog), len(img)))
        for i, (label, regs) in enumerate(prog):
            f.write("# [%d] GEMM_FUSED %s\n" % (i, label))
            for name, v in regs.items():
                addr = B + (R[name] if name in R else 0x46C + 4 * X.index(name))
                f.write("W %08x %x\n" % (addr, v & 0xFFFFFFFF))
            f.write("W 40000310 12\n")
    print("wrote %s: %d instructions, %d bytes used of %d" % (a.out, len(prog), top[0], len(img)))


